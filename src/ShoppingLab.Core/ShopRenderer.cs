using System.Globalization;
using System.IO.Compression;
using System.Net;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace ShoppingLab.Core;

/// <summary>Renders the demo shop: product pages with JSON-LD Product/Offer, robots.txt, sitemap.xml and placeholder images.</summary>
public static class ShopRenderer
{
    public static string ProductPage(ShopScenario shop, PageRecord page)
    {
        var p = page.Product;
        var url = shop.Absolute(shop.ProductPath(p.Slug));
        var canonical = shop.Absolute(page.CanonicalPath ?? shop.ProductPath(p.Slug));
        var image = shop.Absolute(shop.ImagePath(p.Sku + ".png"));
        var color = Text.Color(p.Color);
        var jsonLd = new JsonObject
        {
            ["@context"] = "https://schema.org",
            ["@type"] = "Product",
            ["name"] = p.Title,
            ["description"] = p.Description,
            ["sku"] = p.Sku,
            ["gtin13"] = p.Gtin,
            ["image"] = image,
            ["color"] = color.Masculine,
            ["category"] = p.CategoryPath,
            ["brand"] = new JsonObject { ["@type"] = "Brand", ["name"] = p.Brand },
        };
        if (page.JsonLdOffer)
        {
            jsonLd["offers"] = new JsonObject
            {
                ["@type"] = "Offer",
                ["url"] = url,
                ["price"] = p.Price.ToString("0.00", CultureInfo.InvariantCulture),
                ["priceCurrency"] = p.Currency,
                ["availability"] = p.InStock ? "https://schema.org/InStock" : "https://schema.org/OutOfStock",
                ["itemCondition"] = "https://schema.org/NewCondition",
                ["seller"] = new JsonObject { ["@type"] = "Organization", ["name"] = CatalogGenerator.SellerName },
            };
        }
        var json = jsonLd.ToJsonString(new JsonSerializerOptions { WriteIndented = true, Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping })
            .Replace("</", "<\\/");
        var robots = page.NoIndex ? "noindex, nofollow" : "index, follow";
        var stock = p.InStock ? "Dostępny" : "Niedostępny";
        var price = p.Price.ToString("0.00", CultureInfo.GetCultureInfo("pl-PL"));
        return $$"""
            <!doctype html>
            <html lang="pl">
            <head>
            <meta charset="utf-8">
            <meta name="viewport" content="width=device-width, initial-scale=1">
            <title>{{H(p.Title)}} | {{H(CatalogGenerator.SellerName)}}</title>
            <meta name="description" content="{{H(p.Description)}}">
            <meta name="robots" content="{{robots}}">
            <link rel="canonical" href="{{H(canonical)}}">
            <script type="application/ld+json">
            {{json}}
            </script>
            <style>body{font-family:system-ui,sans-serif;max-width:760px;margin:2rem auto;padding:0 1rem;color:#1a1a1a}
            .demo{background:#fff4d6;border:1px solid #e8c766;padding:.5rem .75rem;border-radius:6px;font-size:.9rem}
            .card{display:flex;gap:1.5rem;align-items:flex-start;margin-top:1.5rem}img{border-radius:8px;border:1px solid #ddd}
            .price{font-size:1.6rem;font-weight:700}.out{color:#a40000}.in{color:#1b6e2f}dl{display:grid;grid-template-columns:auto 1fr;gap:.25rem 1rem}</style>
            </head>
            <body>
            <p class="demo">Demo store page generated by AI Shopping Readiness Lab. Fictional product, not for sale. Scenario: <strong>{{H(shop.Key)}}</strong>.</p>
            <nav><a href="{{H(shop.Absolute(shop.ShopPath + "/"))}}">← {{H(CatalogGenerator.SellerName)}}</a></nav>
            <main class="card">
            <img src="{{H(image)}}" width="200" height="200" alt="{{H(p.Title)}}">
            <div>
            <h1>{{H(p.Title)}}</h1>
            <p class="price">{{price}} zł</p>
            <p class="{{(p.InStock ? "in" : "out")}}">{{stock}}</p>
            <p>{{H(p.Description)}}</p>
            <dl><dt>SKU</dt><dd>{{H(p.Sku)}}</dd><dt>Marka</dt><dd>{{H(p.Brand)}}</dd><dt>Kolor</dt><dd>{{H(color.Masculine)}}</dd><dt>GTIN</dt><dd>{{H(p.Gtin)}}</dd></dl>
            </div>
            </main>
            </body>
            </html>
            """;
    }

    public static string ShopIndex(ShopScenario shop)
    {
        var rows = new StringBuilder();
        foreach (var page in shop.PagesBySlug.Values.OrderBy(p => p.Product.Sku, StringComparer.Ordinal))
        {
            var p = page.Product;
            rows.Append(CultureInfo.InvariantCulture, $"<li><a href=\"{H(shop.Absolute(shop.ProductPath(p.Slug)))}\">{H(p.Title)}</a> <small>{H(p.Sku)}</small></li>\n");
        }
        return $"""
            <!doctype html><html lang="pl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
            <title>{H(CatalogGenerator.SellerName)} ({H(shop.Key)})</title><meta name="robots" content="noindex">
            <style>body{"{"}font-family:system-ui,sans-serif;max-width:900px;margin:2rem auto;padding:0 1rem{"}"}</style></head>
            <body><h1>{H(CatalogGenerator.SellerName)} — scenario “{H(shop.Key)}”</h1><p>{H(shop.Label)}. All products are fictional.</p>
            <p><a href="{H(shop.Absolute(shop.ShopPath + "/feed.jsonl"))}">feed.jsonl</a> · <a href="{H(shop.Absolute(shop.ShopPath + "/robots.txt"))}">robots.txt</a> · <a href="{H(shop.Absolute(shop.ShopPath + "/sitemap.xml"))}">sitemap.xml</a></p>
            <ul>{rows}</ul></body></html>
            """;
    }

    public static string Sitemap(ShopScenario shop)
    {
        var builder = new StringBuilder("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n");
        foreach (var slug in shop.SitemapSlugs.Order(StringComparer.Ordinal))
        {
            builder.Append(CultureInfo.InvariantCulture, $"  <url><loc>{H(shop.Absolute(shop.ProductPath(slug)))}</loc></url>\n");
        }
        return builder.Append("</urlset>\n").ToString();
    }

    private static string H(string value) => WebUtility.HtmlEncode(value);

    /// <summary>Solid-color PNG placeholder showing the variant color.</summary>
    public static byte[] Png(string hex, int size = 200)
    {
        var r = Convert.ToByte(hex.Substring(1, 2), 16);
        var g = Convert.ToByte(hex.Substring(3, 2), 16);
        var b = Convert.ToByte(hex.Substring(5, 2), 16);
        var raw = new byte[size * (size * 3 + 1)];
        for (var y = 0; y < size; y++)
        {
            var row = y * (size * 3 + 1);
            for (var x = 0; x < size; x++)
            {
                var border = x < 6 || y < 6 || x >= size - 6 || y >= size - 6;
                var i = row + 1 + x * 3;
                raw[i] = border ? (byte)(r * 0.7) : r;
                raw[i + 1] = border ? (byte)(g * 0.7) : g;
                raw[i + 2] = border ? (byte)(b * 0.7) : b;
            }
        }
        using var output = new MemoryStream();
        output.Write([137, 80, 78, 71, 13, 10, 26, 10]);
        var header = new byte[13];
        WriteInt(header, 0, size);
        WriteInt(header, 4, size);
        header[8] = 8;
        header[9] = 2;
        Chunk(output, "IHDR", header);
        using (var compressed = new MemoryStream())
        {
            using (var z = new ZLibStream(compressed, CompressionLevel.Optimal, leaveOpen: true))
            {
                z.Write(raw);
            }
            Chunk(output, "IDAT", compressed.ToArray());
        }
        Chunk(output, "IEND", []);
        return output.ToArray();
    }

    private static void Chunk(Stream output, string type, byte[] data)
    {
        var length = new byte[4];
        WriteInt(length, 0, data.Length);
        output.Write(length);
        var typeBytes = Encoding.ASCII.GetBytes(type);
        output.Write(typeBytes);
        output.Write(data);
        var crc = new byte[4];
        WriteInt(crc, 0, (int)Crc32([.. typeBytes, .. data]));
        output.Write(crc);
    }

    private static void WriteInt(byte[] buffer, int offset, int value)
    {
        buffer[offset] = (byte)(value >> 24);
        buffer[offset + 1] = (byte)(value >> 16);
        buffer[offset + 2] = (byte)(value >> 8);
        buffer[offset + 3] = (byte)value;
    }

    private static uint Crc32(byte[] data)
    {
        var crc = 0xFFFFFFFFu;
        foreach (var value in data)
        {
            crc ^= value;
            for (var k = 0; k < 8; k++)
            {
                crc = (crc & 1) != 0 ? 0xEDB88320u ^ (crc >> 1) : crc >> 1;
            }
        }
        return ~crc;
    }
}
